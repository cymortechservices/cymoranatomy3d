/**
 * Generates supabase/seed.sql from the bundled content (single source of truth: src/data).
 * Run: npm run seed:generate
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { SYSTEMS } from '../src/data/systems'
import { REGIONS } from '../src/data/regions'
import { ORGANS } from '../src/data/organs'
import { STRUCTURES } from '../src/data/structures'
import { LESSONS } from '../src/data/lessons'
import { HISTOLOGY } from '../src/data/histology'
import { ANIMATIONS } from '../src/data/animations'
import { QUESTIONS } from '../src/data/questions'
import { BUILTIN_BUNDLES, Z_ANATOMY, MODIFICATIONS } from '../src/data/atlas'
import { ATLAS_LINKS, resolveLink } from '../src/lib/atlasLinks'
import { readFileSync } from 'node:fs'

const q = (v: unknown) => `$j$${JSON.stringify(v)}$j$`
// Explicit column list so table defaults (created_at, ...) still apply to columns the data does not set.
const rows = (table: string, data: unknown[]) => {
  if (!data.length) return ''
  const cols = [...new Set(data.flatMap((r) => Object.keys(r as object)))].filter((k) => data.some((r) => (r as Record<string, unknown>)[k] !== undefined))
  const list = cols.map((c) => `"${c}"`).join(', ')
  return `insert into public.${table} (${list}) select ${list} from jsonb_populate_recordset(null::public.${table}, ${q(data)}::jsonb) on conflict do nothing;\n`
}
const out: string[] = ['-- GENERATED by scripts/generate-seed.ts. Do not edit by hand.\nbegin;\n']

out.push(rows('systems', SYSTEMS.map((s, i) => ({ ...s, sort_order: i }))))
out.push(rows('regions', REGIONS))
out.push(rows('organs', ORGANS))
out.push(rows('structures', STRUCTURES))
out.push(rows('lessons', LESSONS.map(({ sections: _s, ...l }) => l)))
out.push(rows('lesson_sections', LESSONS.flatMap((l) => l.sections.map((s, i) => ({ lesson_id: l.id, sort_order: i, heading: s.heading, body: s.body, kind: s.kind ?? 'text' })))))
out.push(rows('histology_images', HISTOLOGY.map((h) => ({ id: h.id, name: h.name, classification: h.classification, data: h }))))
out.push(rows('animations', ANIMATIONS.map(({ ...a }) => a)))
const topics = [...new Set(QUESTIONS.map((x) => x.topic))]
out.push(rows('quizzes', topics.map((t) => ({ id: `quiz-${t}`, title: `${t[0].toUpperCase()}${t.slice(1)} quiz`, topic: t }))))
out.push(rows('questions', QUESTIONS.map((x) => ({ id: x.id, quiz_id: `quiz-${x.topic}`, type: x.type, topic: x.topic, difficulty: x.difficulty, prompt: x.prompt, explanation: x.explanation, correct: x.correct ?? null, structure_id: x.structure_id ?? null,
  payload: { accepted: x.accepted, pairs: x.pairs, pin_answers: x.pin_answers, diagram: x.diagram, highlight_pin: x.highlight_pin } }))))
out.push(rows('question_options', QUESTIONS.flatMap((x) => (x.options ?? []).map((o, i) => ({ question_id: x.id, option_id: o.id, text: o.text, sort_order: i })))))

// Built-in model registry: metadata and credits. file_url stays null because the app ships these files.
out.push(rows('anatomical_models', BUILTIN_BUNDLES.map((b) => ({
  id: b.id, name: b.title, system_id: b.system, file_format: 'glb', origin: 'builtin', creator: Z_ANATOMY.creator, source: Z_ANATOMY.source, source_url: Z_ANATOMY.source_url,
  licence_name: Z_ANATOMY.licence, licence_url: Z_ANATOMY.licence_url, attribution: Z_ANATOMY.attribution, modified: true, modification_notes: MODIFICATIONS,
  mesh_count: b.mesh_count, tris_out: b.tris_out, bbox: b.bbox, size_bytes: b.bytes, sha256: b.sha256, verification_status: b.verification.status === 'verified' ? 'verified' : 'unverified',
  verified_at: b.verification.checked_at ?? null,
}))))
const maps: unknown[] = []
for (const [sid, link] of Object.entries(ATLAS_LINKS)) {
  const m = JSON.parse(readFileSync(`public/models/zanatomy/${link.bundle}.json`, 'utf8')).meshes
  for (const id of resolveLink(link, m)) maps.push({ model_id: link.bundle, mesh_id: id, structure_id: sid })
}
out.push(rows('model_structure_mappings', maps))
out.push('commit;\n')
mkdirSync('supabase', { recursive: true })
writeFileSync('supabase/seed.sql', out.join('\n'))
console.log('seed.sql written:', { systems: SYSTEMS.length, structures: STRUCTURES.length, lessons: LESSONS.length, questions: QUESTIONS.length, models: BUILTIN_BUNDLES.length, mappings: maps.length })
